#!/usr/bin/env node
// Builds the ldvec kernel twice (a SIMD module and a scalar module), both path-remapped, and writes
// src/wasm/ldvec.gen.ts (git-ignored) with the two modules as base64 plus their sha256.
//
//   node scripts/build-wasm.mjs [--check]
//
// target/wasm-simd    cargo build --release --locked --target wasm32-unknown-unknown -p ldvec, +simd128
// target/wasm-scalar  the same without simd128
//
// RUSTFLAGS always carry --remap-path-prefix for the repository root, the cargo home and the rustup
// home (as glyphsift/scripts/remap-paths.sh does), so no builder path reaches a shipped module or
// the tarball (panic locations and debug paths embed them). The flags go through
// CARGO_ENCODED_RUSTFLAGS so a path with spaces survives. wasm-opt is not used: the module is small
// and an extra optimiser would be one more thing to pin for byte-reproducibility.
//
// --check rebuilds both modules and fails unless src/wasm/ldvec.gen.ts already holds exactly their
// bytes (used by scripts/pack-check.mjs: the embedded modules equal a fresh remapped build).
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const GEN = join(repo, 'src', 'wasm', 'ldvec.gen.ts');
const cargoHome = process.env['CARGO_HOME'] ?? join(homedir(), '.cargo');
const rustupHome = process.env['RUSTUP_HOME'] ?? join(homedir(), '.rustup');

const REMAP = [
  `--remap-path-prefix=${repo}=/ldvec`,
  `--remap-path-prefix=${cargoHome}=/cargo`,
  `--remap-path-prefix=${rustupHome}=/rustup`,
];

function build(label, extraFlags) {
  const targetDir = join(repo, 'target', `wasm-${label}`);
  const existing = process.env['CARGO_ENCODED_RUSTFLAGS']
    ? process.env['CARGO_ENCODED_RUSTFLAGS'].split('\x1f').filter(Boolean)
    : [];
  const flags = [...existing, ...extraFlags, ...REMAP].join('\x1f');
  const env = { ...process.env, CARGO_ENCODED_RUSTFLAGS: flags };
  delete env['RUSTFLAGS'];
  const r = spawnSync(
    'cargo',
    [
      'build',
      '--release',
      '--locked',
      '--target',
      'wasm32-unknown-unknown',
      '-p',
      'ldvec',
      '--target-dir',
      targetDir,
    ],
    { cwd: repo, env, stdio: 'inherit' },
  );
  if (r.error) throw new Error(`cargo could not be started: ${r.error.message}`);
  if (r.status !== 0) throw new Error(`cargo build (${label}) failed with status ${r.status}`);
  const wasm = join(targetDir, 'wasm32-unknown-unknown', 'release', 'ldvec.wasm');
  if (!existsSync(wasm)) throw new Error(`expected ${wasm}`);
  return readFileSync(wasm);
}

const simd = build('simd', ['-C', 'target-feature=+simd128']);
const scalar = build('scalar', []);
const sha = (b) => createHash('sha256').update(b).digest('hex');

const body = `// GENERATED by scripts/build-wasm.mjs from crates/ldvec. Git-ignored; do not edit.
// The two modules are the same Rust source built with and without simd128. Their sha256 values are
// of the raw .wasm bytes and reproduce from a fresh build (npm run pack:check).
export const LDVEC_SIMD_B64 = '${simd.toString('base64')}';
export const LDVEC_SCALAR_B64 = '${scalar.toString('base64')}';
export const LDVEC_SIMD_SHA256 = '${sha(simd)}';
export const LDVEC_SCALAR_SHA256 = '${sha(scalar)}';
`;

if (process.argv.includes('--check')) {
  const have = existsSync(GEN) ? readFileSync(GEN, 'utf8') : '';
  if (have !== body) {
    console.error(
      `build-wasm --check: ${GEN} does not hold the freshly built modules ` +
        `(simd ${sha(simd)}, scalar ${sha(scalar)})`,
    );
    process.exit(1);
  }
  console.log(`build-wasm --check: ok (simd ${sha(simd)}, scalar ${sha(scalar)})`);
} else {
  mkdirSync(dirname(GEN), { recursive: true });
  writeFileSync(GEN, body);
  console.log(`[ldvec] simd   ${simd.length} bytes sha256 ${sha(simd)}`);
  console.log(`[ldvec] scalar ${scalar.length} bytes sha256 ${sha(scalar)}`);
  console.log(`[ldvec] wrote ${GEN}`);
}
