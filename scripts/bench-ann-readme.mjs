const quote = (v) => {
  const s = String(v);
  return /[",\n\r]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
};
export const annCsvHeader = () => `${ANN_COLUMNS.join(',')}\n`;
export const annCsvRow = (o) => `${ANN_COLUMNS.map((c) => quote(o[c] ?? '')).join(',')}\n`;

/**
 * The 1-minute load average as a CSV cell: two decimals, and '' on Windows, where os.loadavg() is always 0 and a
 * 0 would read as an idle machine (Sprint 7, quiet slot Q2, TD-124).
 */
export const hostLoadCell = (platform, load) =>
  platform === 'win32' || !Number.isFinite(load) ? '' : String(Math.round(load * 100) / 100);

/** The 1-minute load above which a figure is labelled "measured under load" (the Q2 rule: start load above 4). */
export const LOAD_LIMIT = 4;
export const UNDER_LOAD = 'measured under load';
const underLoad = (r) =>
  Number(r.host_load_1m_start) > LOAD_LIMIT || Number(r.host_load_1m_end) > LOAD_LIMIT;

/** One sentence about the host-load columns of a set of CSV rows, computed from the rows only. */
const loadSentence = (rows) => {
  const xs = rows
    .flatMap((r) => [r.host_load_1m_start, r.host_load_1m_end])
    .filter((v) => v !== undefined && v !== '')
    .map(Number)
    .filter(Number.isFinite);
  if (xs.length === 0)
    return 'The host load columns are empty (they are empty on Windows, where there is no 1-minute load average).';
  const over = rows.filter(underLoad).length;
  if (over === 0)
    return `Host load (the 1-minute load average at the start and the end of each run, from the CSV): lowest ${Math.min(...xs)}, highest ${Math.max(...xs)}; no row has a cell above ${LOAD_LIMIT}.`;
  return `Host load (the 1-minute load average at the start and the end of each run, from the CSV): lowest ${Math.min(...xs)}, highest ${Math.max(...xs)}; ${over} of ${rows.length} rows have a cell above ${LOAD_LIMIT} and their latency cells say "${UNDER_LOAD}". The counter is the operating system's, and a figure above ${LOAD_LIMIT} does not by itself show that the CPU was busy.`;
};

