export const DUP_END = '<!-- ann-dup-bench:end -->';

/** The README block for docs/benchmarks/ann-duplicates.csv, computed from the CSV rows only. */
export function renderAnnDup(rows) {
  const map = new Map();
  for (const r of rows) {
    const k = [r.data, r.rows, r.copies_per_vector, r.ef_search].join('|');
    if (!map.has(k)) map.set(k, []);
    map.get(k).push(r);
  }
  const sums = [...map.values()]
    .map((g) => {
      const f = g[0];
      return {
        data: f.data,
        rows: num(f.rows),
        copies: num(f.copies_per_vector),
        ef: num(f.ef_search),
        runs: g.length,
        queries: num(f.queries),
        build: median(g.map((r) => num(r.build_ms))),
        dup: median(g.map((r) => num(r.duplicate_rows))),
        graph: median(g.map((r) => num(r.answered_by_graph))),
        flatDup: median(g.map((r) => num(r.answered_by_flat_duplicates))),
        equal: median(g.map((r) => num(r.queries_equal_to_flat))),
        recall: median(g.map((r) => num(r.recall_at_10_by_score))),
        p50: median(g.map((r) => num(r.query_p50_ms))),
        p95: median(g.map((r) => num(r.query_p95_ms))),
        ann: median(g.map((r) => num(r.ann_bytes))),
        under: g.some(underLoad),
      };
    })
    .sort((a, b) => a.rows - b.rows || a.copies - b.copies || a.ef - b.ef);
  const first = rows[0];
  const copiesList = [...new Set(sums.map((x) => x.copies))].sort((x, y) => x - y);
  const lines = [];
  lines.push(
    `Measured on ${first.machine} (${first.os}), ${first.chrome}, ${first.kernel} kernel, OPFS, with the command \`${first.command}\` on commit \`${first.commit}\`. Every figure below is computed from [docs/benchmarks/ann-duplicates.csv](docs/benchmarks/ann-duplicates.csv) by \`scripts/bench-ann-readme.mjs\`. The data is the clustered generator of \`bench/synth.ts\` in which every vector is stored ${copiesList.join(' times in one set and ')} times in the other under different keys (so ${sums
      .map((x) => commas(x.dup))
      .filter((v, i, a) => a.indexOf(v) === i)
      .join(
        ' and ',
      )} of ${sums[0] ? commas(sums[0].rows) : 0} rows are exact copies of an earlier row), 384 dimensions, cosine, k = 10, HNSW with m = 16, efConstruction = 200, seed = 1. Copies of one vector tie, so recall is counted by score (a hit counts when its score is at least the flat scan's 10th best score) and "equal to flat" is the number of queries whose ten scores are, as a multiset and bit for bit, the flat scan's. A group of identical rows larger than 2m (32 at m = 16, the capacity of a layer-0 neighbour list) makes the graph degenerate and the exact flat scan answers with fallback \`duplicates\`: the columns "Answered by the graph" and "Answered by flat (duplicates)" say which path answered each row, so the set whose groups are within 2m is answered by the graph and the one whose groups are not is answered by the flat scan. A group of rows that share one quantised key (the same vector up to the low 12 mantissa bits of every component) larger than 2m makes a graph degenerate in the same way (TD-126); this CSV has no column for it, and the same data was rebuilt natively after that rule (\`scale_duplicates_100k\` in \`crates/ldvec/tests/hnsw_dup.rs\`) with the same outcome: 30 copies not degenerate, 60 degenerate. The 8 GB Windows no-GPU laptop column is ${EIGHT_GB}.`,
  );
  lines.push('');
  lines.push(
    '| Data | Rows | Copies per vector | ef | Runs | Build (ms) | Answered by the graph | Answered by flat (duplicates) | Equal to flat | Recall@10 by score | Query p50 (ms) | Query p95 (ms) | Graph (MB) | 8 GB Windows no-GPU laptop |',
  );
  lines.push(
    '| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | --- |',
  );
  for (const s of sums) {
    lines.push(
      `| ${s.data} | ${commas(s.rows)} | ${s.copies} | ${s.ef} | ${s.runs} | ${loaded(fmtMs(s.build), s.under)} | ${s.graph} of ${s.queries} | ${s.flatDup} of ${s.queries} | ${s.equal} of ${s.queries} | ${fmtRecall(s.recall)} | ${loaded(fmtMs(s.p50), s.under)} | ${loaded(fmtMs(s.p95), s.under)} | ${fmtMB(s.ann)} | ${EIGHT_GB} |`,
    );
  }
  lines.push('');
  lines.push(loadSentence(rows));
  lines.push('');
  lines.push(
    'The floors were stated before measuring (TD-109): at ef 64, at least 99 of 100 queries equal to flat and a mean recall@10 by score of at least 0.99. `test/readme-ann-bench.test.ts` reads them from this CSV. Nothing here is an 8 GB figure.',
  );
  return lines.join('\n');
}

export const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const ANN_CSV = join(repoRoot, 'docs', 'benchmarks', 'ann.csv');
export const ANN_NOTE = join(repoRoot, 'docs', 'benchmarks', 'ann-notes.json');
export const ANN_DUP_CSV = join(repoRoot, 'docs', 'benchmarks', 'ann-duplicates.csv');

export function readAnnNote(path = ANN_NOTE) {
  return existsSync(path) ? JSON.parse(readFileSync(path, 'utf8')) : undefined;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const rows = parseCsv(readFileSync(ANN_CSV, 'utf8'));
  if (rows.length === 0) throw new Error('docs/benchmarks/ann.csv has no rows');
  const block = renderAnnBench(rows, readAnnNote());
  const dupRows = existsSync(ANN_DUP_CSV) ? parseCsv(readFileSync(ANN_DUP_CSV, 'utf8')) : [];
  const dupBlock = dupRows.length > 0 ? renderAnnDup(dupRows) : undefined;
  if (process.argv.includes('--write')) {
    const readme = join(repoRoot, 'README.md');
    let text = readFileSync(readme, 'utf8');
    const swap = (begin, end, body) => {
      const a = text.indexOf(begin);
      const b = text.indexOf(end);
      if (a < 0 || b < a)
        throw new Error(`README.md has no ${begin.slice(0, 30)} ... ${end} markers`);
      text = `${text.slice(0, a)}${begin}\n\n${body}\n\n${text.slice(b)}`;
    };
    swap(BEGIN, END, block);
    if (dupBlock !== undefined) swap(DUP_BEGIN, DUP_END, dupBlock);
    writeFileSync(readme, text);
    console.log('README.md HNSW benchmark blocks rewritten from the CSVs');
  } else console.log(dupBlock === undefined ? block : `${block}\n\n${dupBlock}`);
}
