const num = (v) => Number(v);
const median = (xs) => {
  const s = [...xs].sort((a, b) => a - b);
  const m = s.length >> 1;
  return s.length % 2 ? s[m] : (s[m - 1] + s[m]) / 2;
};
const fmtMs = (x) => (x >= 1000 ? x.toFixed(0) : x >= 100 ? x.toFixed(0) : x.toFixed(2));
const loaded = (cell, flag) => (flag ? `${cell} (${UNDER_LOAD})` : cell);
const fmtMB = (b) => `${(b / 1e6).toFixed(1)}`;
const fmtRecall = (r) => r.toFixed(3);
const commas = (n) => Number(n).toLocaleString('en-US');

/** One summary per (data, rows, index kind, ef): medians over the runs. In a stable order. */
export function summariseAnn(rows) {
  const map = new Map();
  for (const r of rows) {
    const k = [r.data, r.rows, r.index_kind, r.ef_search].join('|');
    if (!map.has(k)) map.set(k, []);
    map.get(k).push(r);
  }
  const kindOrder = { flat: 0, hnsw: 1 };
  const dataOrder = { clustered: 0, uniform: 1 };
  const out = [...map.values()].map((g) => {
    const f = g[0];
    return {
      data: f.data,
      rows: num(f.rows),
      kind: f.index_kind,
      m: f.m === '' ? null : num(f.m),
      efc: f.ef_construction === '' ? null : num(f.ef_construction),
      ef: f.ef_search === '' ? null : num(f.ef_search),
      runs: g.length,
      build: median(g.map((r) => num(r.build_ms))),
      open: median(g.map((r) => num(r.cold_open_ms))),
      p50: median(g.map((r) => num(r.query_p50_ms))),
      p95: median(g.map((r) => num(r.query_p95_ms))),
      recall: median(g.map((r) => num(r.recall_at_10))),
      recallMin: Math.min(...g.map((r) => num(r.recall_at_10))),
      index: median(g.map((r) => num(r.index_bytes))),
      ann: median(g.map((r) => num(r.ann_bytes))),
      wasm: median(g.map((r) => num(r.wasm_memory_bytes))),
      heap: median(g.map((r) => num(r.js_heap_peak_bytes))),
      under: g.some(underLoad),
    };
  });
  return out.sort(
    (a, b) =>
      dataOrder[a.data] - dataOrder[b.data] ||
      a.rows - b.rows ||
      kindOrder[a.kind] - kindOrder[b.kind] ||
      (a.ef ?? 0) - (b.ef ?? 0),
  );
}

/** The README block, generated from the CSV rows and the optional 1M note only. */
export function renderAnnBench(rows, note) {
  const sums = summariseAnn(rows);
  const first = rows[0];
  const lines = [];
  lines.push(
    `Measured on ${first.machine} (${first.os}), ${first.chrome}, ${first.kernel} kernel, OPFS, with the command \`${first.command}\` on commit \`${first.commit}\`. Every figure below is computed from [docs/benchmarks/ann.csv](docs/benchmarks/ann.csv) by \`scripts/bench-ann-readme.mjs\`; the CSV holds one row per run and per index kind, with the machine and the command on every row. The 8 GB Windows no-GPU laptop column is ${EIGHT_GB} (owner step): nothing here is an 8 GB figure. Chrome was launched with \`--enable-precise-memory-info\`.`,
  );
  lines.push('');
  lines.push(
    'The data is the integer-only clustered generator of `bench/synth.ts` (the same bytes in Rust and TypeScript; 1,000 centres for 100,000 rows) or, for the "uniform" rows, the uniform generator of the flat benchmark, which is the worst case for any graph index. 384 dimensions, cosine, k = 10, 200 queries per run; HNSW with m = 16, efConstruction = 200, seed = 1. Recall@10 is the overlap of the HNSW top 10 with the flat scan top 10 of the same store. Medians over the runs; `build` is the `putVectors` write time for flat rows and the `buildIndex` time (on top of the write) for HNSW rows; `cold open` is `createStore` plus the first query of the kind in a fresh page (it includes loading the vectors, and the graph for HNSW). The flat rows are measured in a page that never loads the graph, so their WASM memory and JS heap columns are the flat index alone; `storage_usage_bytes` in the CSV is the whole namespace (flat index and graph) on every row.',
  );
  lines.push('');
  lines.push(
    '| Data | Rows | Index | ef | Runs | Build (ms) | Cold open (ms) | Query p50 (ms) | Query p95 (ms) | Recall@10 | Graph (MB) | Flat index (MB) | WASM memory (MB) | JS heap peak (MB) | 8 GB Windows no-GPU laptop |',
  );
  lines.push(
    '| --- | ---: | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | --- |',
  );
  for (const s of sums) {
    lines.push(
      `| ${s.data} | ${commas(s.rows)} | ${s.kind} | ${s.ef === null ? '-' : s.ef} | ${s.runs} | ${loaded(fmtMs(s.build), s.under)} | ${loaded(fmtMs(s.open), s.under)} | ${loaded(fmtMs(s.p50), s.under)} | ${loaded(fmtMs(s.p95), s.under)} | ${fmtRecall(s.recall)} | ${s.kind === 'hnsw' ? fmtMB(s.ann) : '-'} | ${fmtMB(s.index)} | ${fmtMB(s.wasm)} | ${fmtMB(s.heap)} | ${EIGHT_GB} |`,
    );
  }
  lines.push('');
  const target = sums.find(
    (s) => s.data === 'clustered' && s.kind === 'hnsw' && s.ef === 128 && s.rows === 100000,
  );
  if (target) {
    lines.push(
      `Recall target (stated before measuring: at least 0.90 at ef = 128 on the 100,000 x 384 clustered set): median ${fmtRecall(target.recall)}, lowest run ${fmtRecall(target.recallMin)}, so the target is ${target.recallMin >= 0.9 ? 'met' : target.recall >= 0.9 ? 'met by the median and missed by the lowest run' : 'MISSED'}. The generator was not changed after the numbers were seen.`,
    );
    lines.push('');
  }
  if (note?.oneMillion) {
    lines.push(`1,000,000 x 384: ${note.oneMillion.statement}`);
    lines.push('');
  }
  lines.push(loadSentence(rows));
  lines.push('');
  lines.push(
    `All of this is Apple M5 Pro, 48 GB; ${EIGHT_GB}. Quantisation, compaction and encryption at rest are not done, so the graph sits on top of the full-precision vectors and the memory columns show it.`,
  );
  return lines.join('\n');
}

