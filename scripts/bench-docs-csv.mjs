// Shared by bench/documents-bench.spec.ts (which writes docs/benchmarks/documents.csv), by
// scripts/bench-docs-readme.mjs and by test/readme-docs-bench.test.ts: the CSV columns, and the one
// function that turns CSV rows into the README "Documents benchmark" block. Nothing in the README numbers
// is typed by hand: they are computed here from the CSV and nothing else. Every figure is from an Apple
// M5 Pro with 48 GB; the eight_gb column of every row reads "not measured on 8 GB".
