export const COLUMNS = [
  'commit',
  'date_utc',
  'machine',
  'os',
  'chrome',
  'precise_memory',
  'command',
  'driver',
  'kernel',
  'operation',
  'docs',
  'chunks_per_doc',
  'dim',
  'chunk_text_bytes',
  'restart',
  'run',
  'ops',
  'total_ms',
  'per_op_ms',
  'p50_ms',
  'p95_ms',
  'js_heap_peak_bytes',
  'wasm_memory_bytes',
  'index_bytes',
  'storage_usage_bytes',
  'match',
  'eight_gb',
];

export const EIGHT_GB = 'not measured on 8 GB';
export const OPERATIONS = ['put', 'query_warm', 'query_cold', 'delete', 'clear'];

const quote = (v) => {
  const s = String(v);
  return /[",\n\r]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
};

export const csvHeader = () => `${COLUMNS.join(',')}\n`;
export const csvRow = (o) => `${COLUMNS.map((c) => quote(o[c] ?? '')).join(',')}\n`;

const num = (v) => Number(v);
const median = (xs) => {
  const s = [...xs].sort((a, b) => a - b);
  const m = s.length >> 1;
  return s.length % 2 ? s[m] : (s[m - 1] + s[m]) / 2;
};
const worst = (xs) => Math.max(...xs);
const fmtMs = (x) => (x >= 100 ? x.toFixed(0) : x >= 10 ? x.toFixed(1) : x.toFixed(2));
const fmtMB = (b) => `${(b / 1e6).toFixed(1)} MB`;

/** One summary per (driver, operation): medians over the non-restart runs, and the restart run. */
export function summarise(rows) {
  const out = [];
  const drivers = [...new Set(rows.map((r) => r.driver))];
  for (const driver of drivers) {
    for (const operation of OPERATIONS) {
      const g = rows.filter((r) => r.driver === driver && r.operation === operation);
      if (g.length === 0) continue;
      const runs = g.filter((r) => r.restart !== 'true');
      const restart = g.find((r) => r.restart === 'true');
      const basis = runs.length > 0 ? runs : g;
      out.push({
        driver,
        operation,
        n: runs.length,
        ops: num(basis[0].ops),
        total: median(basis.map((r) => num(r.total_ms))),
        perOp: median(basis.map((r) => num(r.per_op_ms))),
        p50: median(basis.map((r) => num(r.p50_ms))),
        p95: median(basis.map((r) => num(r.p95_ms))),
        worstTotal: worst(basis.map((r) => num(r.total_ms))),
        heap: [
          median(basis.map((r) => num(r.js_heap_peak_bytes))),
          worst(basis.map((r) => num(r.js_heap_peak_bytes))),
        ],
        wasm: [
          median(basis.map((r) => num(r.wasm_memory_bytes))),
          worst(basis.map((r) => num(r.wasm_memory_bytes))),
        ],
        restartMs: restart ? num(restart.total_ms) : undefined,
        allMatch: g.every((r) => r.match === 'true'),
      });
    }
  }
  return out;
}

const NAMES = {
  put: 'putDocument, one document of 200 chunks',
  query_warm: 'queryChunks, k = 5, index resident',
  query_cold: 'createStore + first queryChunks, k = 5 (fresh page)',
  delete: 'deleteDocument, one document',
  clear: 'clear(ns), the whole namespace',
};

/** The README block, generated from the CSV rows only. */
export function renderDocsBench(rows) {
  const first = rows[0];
  const sums = summarise(rows);
  const lines = [];
  lines.push(
    `Measured on ${first.machine} (${first.os}), ${first.chrome}, ${first.kernel} kernel, on the uncommitted Sprint 5 working tree based on ${String(first.commit).replace(/-dirty$/, '')} (CSV commit column \`${first.commit}\`). Command: \`${first.command}\`. Corpus: ${first.docs} documents x ${first.chunks_per_doc} chunks x ${first.dim} dims, ${first.chunk_text_bytes}-byte chunk texts, one namespace, synthetic (\`bench/synth.ts\`; no real document, no model). Every figure below is computed from [docs/benchmarks/documents.csv](docs/benchmarks/documents.csv) by \`scripts/bench-docs-readme.mjs\`. **${EIGHT_GB}**: nothing here is an 8 GB figure, and the OS file cache cannot be dropped from a page, so a "cold" run is cold for the page, the JS heap and the WebAssembly instance, not for the disk cache. Chrome was launched with \`--enable-precise-memory-info\`; "JS heap peak" is the main-thread \`performance.memory.usedJSHeapSize\` sampled every 10 ms during the operation (it is not process memory).`,
  );
  lines.push('');
  lines.push(
    '| Operation | Driver | Runs | Operations per run | Total, median (ms) | Per operation, median (ms) | p50 (ms) | p95 (ms) | After a browser restart (ms) | JS heap peak, median / worst | WASM memory, median / worst | 8 GB laptop |',
  );
  lines.push('| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | --- |');
  for (const s of sums) {
    const pair = ([m, w]) => (m === 0 && w === 0 ? '-' : `${fmtMB(m)} / ${fmtMB(w)}`);
    lines.push(
      `| ${NAMES[s.operation]} | ${s.driver} | ${s.n} | ${s.ops} | ${fmtMs(s.total)} | ${fmtMs(s.perOp)} | ${fmtMs(s.p50)} | ${fmtMs(s.p95)} | ${s.restartMs === undefined ? '-' : fmtMs(s.restartMs)} | ${pair(s.heap)} | ${pair(s.wasm)} | ${EIGHT_GB} |`,
    );
  }
  lines.push('');
  const bad = sums.filter((s) => !s.allMatch);
  lines.push(
    bad.length === 0
      ? 'Every query and every post-delete query in the table returned the same top 5 as a naive reference computed outside the timing; every `clear(ns)` row found 0 files or records, and 0 hits, afterwards.'
      : `WARNING: the top 5 did not match the naive reference for ${bad.map((s) => `${s.driver}/${s.operation}`).join(', ')}.`,
  );
  return lines.join('\n');
}
